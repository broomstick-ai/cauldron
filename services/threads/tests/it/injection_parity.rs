//! **THE BYTE-FOR-BYTE PARITY PROOF for the flag flattening.**
//!
//! The operator asked for "parity in behavior + the new context ID" when
//! `inject_context` + `metadata_level` were replaced by one flag per injected
//! thing. A rename that quietly moved a byte of what the model sees would be
//! the worst available outcome, so parity is not argued here, it is DIFFED.
//!
//! `tests/fixtures/injection-parity.golden` is the file [`render_all`] produced
//! **at `7888ec4`, through the old `inject_context` / `metadata_level` code
//! path**, before any flag existed. It is committed as a fixture and is never
//! regenerated afterwards: every scenario in [`render_all`] is now built from
//! the NEW flags at their DEFAULTS, and the test asserts the bytes are
//! identical to what the old settings produced. If the golden is ever
//! regenerated in the same commit that changes a renderer, the proof is
//! worthless — so regeneration is deliberately gated behind an env var.
//!
//! Generated with:
//!
//! ```text
//! THREADS_REGEN_PARITY_GOLDEN=1 cargo test -p threads --test it injection_parity::
//! ```
//!
//! Every stamp is pinned from LOCAL wall clock (`local_at`), so the rendered
//! text is timezone-independent: the fixture is constructed in local time and
//! rendered back into local time.

use chrono::{DateTime, TimeZone, Utc};
use serde_json::json;
use threads::context::{
    build_prompt_body, compaction_restatement, first_turn_preamble, plugins_changed_preamble,
    validate_declarations, MetadataPolicy, PromptSection,
};
use threads::settings::Injection;

/// The committed fixture. Generated by the OLD code path; compared against by
/// the NEW one.
const GOLDEN_PATH: &str = concat!(
    env!("CARGO_MANIFEST_DIR"),
    "/tests/fixtures/injection-parity.golden"
);

fn local_at(y: i32, mo: u32, d: u32, h: u32, mi: u32, s: u32) -> DateTime<Utc> {
    chrono::Local
        .with_ymd_and_hms(y, mo, d, h, mi, s)
        .unwrap()
        .with_timezone(&Utc)
}

/// Far enough ahead that no fixture stamp reads as a capacity prediction, so
/// CON-22's scanner never redacts a golden line.
fn now() -> DateTime<Utc> {
    local_at(2030, 1, 1, 0, 0, 0)
}

const TID: &str = "117d80e2-7c74-4054-96f1-e113ab37c245";

fn section(message_id: u64, ts: DateTime<Utc>, text: &str) -> PromptSection {
    PromptSection {
        message_id,
        ts,
        text: text.into(),
        duration: None,
        idx: None,
        headers: Vec::new(),
    }
}

// ═════════════════════════════════════════════════════════════════════════
// THE THREE POLICY BUILDERS — the ONLY thing that differs between the old
// code path and the new one. Everything below is identical input.
// ═════════════════════════════════════════════════════════════════════════

/// **TODAY'S DEFAULT.** The golden was generated with this builder reading
/// `level: MetadataLevel::default()` on a thread with `inject_context: true`.
/// It now reads `Injection::default()`, and the bytes must be identical.
fn policy_default<'a>(state_thread_id: bool, last_date: Option<&str>) -> MetadataPolicy<'a> {
    MetadataPolicy {
        inject: Injection::default(),
        thread_id: TID,
        state_thread_id,
        context_id: None,
        // The golden's scenarios 4 and 5 were generated when the context line
        // rode `state_thread_id`. It now has its own predicate, and the two
        // agree on every boundary post — which is what keeps those two
        // scenarios byte-identical.
        state_context_id: state_thread_id,
        last_date: last_date.map(str::to_string),
        now: now(),
        app: None,
    }
}

/// **TODAY'S OPTED-IN SHAPE**: the default plus `inject_context_id: true`.
/// This is the only configuration in which the `context:` line has ever been
/// rendered, so it is pinned alongside the default.
fn policy_with_context_id<'a>(state_thread_id: bool, cid: &'a str) -> MetadataPolicy<'a> {
    MetadataPolicy {
        inject: Injection {
            context_id: true,
            ..Injection::default()
        },
        context_id: Some(cid),
        ..policy_default(state_thread_id, None)
    }
}

/// **TODAY'S `metadata_level: none`**, which is also what `inject_context:
/// false` routed through. Under the NEW flags this is every metadata-line flag
/// plus the queue lead-in switched off — the migration target for a stored
/// `metadata_level: none`, and the shape whose parity matters most, because a
/// thread already on disk asked for it.
fn policy_no_metadata<'a>(state_thread_id: bool) -> MetadataPolicy<'a> {
    let mut inject = Injection::default();
    inject.thread_id = false;
    inject.context_id = false;
    inject.message_id = false;
    inject.app_idx = false;
    inject.timestamp = false;
    inject.duration = false;
    inject.queue_lead_in = false;
    MetadataPolicy {
        inject,
        ..policy_default(state_thread_id, None)
    }
}

/// `inject_context: false` ALSO stripped every application-declared header
/// before the body was built — the RUNTIME did it by hand, by emptying each
/// section's `headers`, on a second code path that could drift from the real
/// one. It is now `Injection::application_headers`, so the golden's
/// header-stripped scenario is reproduced by the FLAG. The sections handed in
/// are identical either way; only the gate moved.
fn without_headers<'a>(mut p: MetadataPolicy<'a>) -> MetadataPolicy<'a> {
    p.inject.application_headers = false;
    p
}

// ═════════════════════════════════════════════════════════════════════════
// THE FIXTURE SECTIONS. Functions rather than values because `PromptSection`
// is deliberately not `Clone` and several scenarios consume the same shape.
