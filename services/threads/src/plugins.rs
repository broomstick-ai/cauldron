//! Plugin rollup + hot reload (Q9, §12).
//!
//! Ported from AUI's `collect_plugin_dirs` (libs/aui-nav/src/claude.rs): a dir
//! counts as a plugin when it holds a `.claude-plugin/plugin.{json,yaml}`
//! manifest; scanned roots are attached in order (project tier before global
//! tier), de-duplicated by canonical path.
//!
//! **Hot reload**: because the daemon spawns `claude -p` per turn and this
//! module re-scans the roots + re-snapshots manifest mtimes on EVERY spawn,
//! an edited skill/subcommand reaches the very next turn with no watcher —
//! which is exactly the operator's requirement ("updated skill files visible
//! to agents as fast as possible"). A change between turns is surfaced as a
//! `PluginsChanged` ledger event and triggers a plugin-path restatement in the
//! next prompt. SEAM: if threads later holds a persistent stream-json session,
//! swap the per-spawn rescan for an fs watcher feeding the same
//! [`diff_snapshots`] — the event and restatement plumbing already exist.
//!
//! **Marketplace auto-build** (§12: "given a plugin dir without a marketplace,
//! threads builds the marketplace"): an EXPLICITLY attached `plugin_dirs`
//! entry missing its `.claude-plugin/plugin.json` gets a minimal manifest
//! generated in place ([`ensure_manifest`]). Scanned roots never get this —
//! the manifest is their opt-in gate. AUI itself has no marketplace builder to
//! port (verified by search), so this minimal-manifest shape defines the
//! interface; extend it to `marketplace.json` collections when one exists.

use std::collections::{BTreeMap, HashSet};
use std::path::{Path, PathBuf};
use std::time::SystemTime;

use crate::settings::ThreadSettings;

/// A dir counts as a plugin if it holds a plugin manifest. Follows symlinks.
fn is_plugin(p: &Path) -> bool {
    p.is_dir()
        && (p.join(".claude-plugin/plugin.json").exists()
            || p.join(".claude-plugin/plugin.yaml").exists())
}

/// Generate a minimal `.claude-plugin/plugin.json` for an explicitly attached
/// plugin dir that lacks one. Returns true when a manifest was created.
pub fn ensure_manifest(dir: &Path) -> bool {
    if is_plugin(dir) || !dir.is_dir() {
        return false;
    }
    let name = dir
        .file_name()
        .map(|n| n.to_string_lossy().to_string())
        .unwrap_or_else(|| "plugin".to_string());
    let manifest_dir = dir.join(".claude-plugin");
    if std::fs::create_dir_all(&manifest_dir).is_err() {
        return false;
    }
    let manifest = serde_json::json!({
        "name": name,
        "version": "0.0.0",
        "description": format!("Auto-generated by the threads daemon for {}", dir.display()),
    });
    std::fs::write(
        manifest_dir.join("plugin.json"),
        serde_json::to_string_pretty(&manifest).unwrap_or_default(),
    )
    .is_ok()
}

/// Resolve the effective plugin dir list for one turn: explicit `plugin_dirs`
/// first (auto-manifested when missing), then each `plugin_roots` entry's
/// manifest-bearing children, deduped by canonical path.
pub fn collect_plugin_dirs(settings: &ThreadSettings) -> Vec<PathBuf> {
    let mut dirs: Vec<PathBuf> = Vec::new();
    let mut seen: HashSet<PathBuf> = HashSet::new();
    let mut push = |dirs: &mut Vec<PathBuf>, p: PathBuf| {
        let key = p.canonicalize().unwrap_or_else(|_| p.clone());
        if seen.insert(key) {
            dirs.push(p);
        }
    };

    for d in &settings.plugin_dirs {
        let p = PathBuf::from(d);
        ensure_manifest(&p);
        if is_plugin(&p) {
            push(&mut dirs, p);
        } else {
            tracing::warn!(path = %p.display(), "attached plugin dir is not a plugin — skipped");
        }
    }

    for root in &settings.plugin_roots {
        let root = PathBuf::from(root);
        if let Ok(entries) = std::fs::read_dir(&root) {
            for e in entries.flatten() {
                let p = e.path();
                if is_plugin(&p) {
                    push(&mut dirs, p);
                }
            }
        }
    }

    dirs
}

/// Snapshot of plugin config-file mtimes, for between-turn change detection.
pub type PluginSnapshot = BTreeMap<PathBuf, SystemTime>;

/// Snapshot the mtimes of each plugin's config surfaces (manifest + hooks +
/// the skills/commands trees' dir mtimes — cheap, not a deep walk).
pub fn snapshot(plugin_dirs: &[PathBuf]) -> PluginSnapshot {
    let mut map = BTreeMap::new();
    for dir in plugin_dirs {
        for rel in &[
            ".claude-plugin/plugin.json",
            ".claude-plugin/plugin.yaml",
            "hooks/hooks.json",
            "skills",
            "commands",
            "agents",
        ] {
            let p = dir.join(rel);
            if let Ok(meta) = std::fs::metadata(&p) {
                if let Ok(mtime) = meta.modified() {
                    map.insert(p, mtime);
                }
            }
        }
    }
    map
}

/// Diff two snapshots into `(added, removed, modified)` path lists — the
/// payload of the `PluginsChanged` event.
pub fn diff_snapshots(
    old: &PluginSnapshot,
    new: &PluginSnapshot,
) -> (Vec<String>, Vec<String>, Vec<String>) {
    let mut added = Vec::new();
    let mut removed = Vec::new();
    let mut modified = Vec::new();
    for (p, mt) in new {
        match old.get(p) {
            None => added.push(p.display().to_string()),
            Some(old_mt) if old_mt != mt => modified.push(p.display().to_string()),
            _ => {}
        }
    }
    for p in old.keys() {
        if !new.contains_key(p) {
            removed.push(p.display().to_string());
        }
    }
    (added, removed, modified)
}
