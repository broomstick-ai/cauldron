//! `shapes-manifest` — **WHAT THIS PRODUCER DECLARES, OFFLINE, AS `shapes.list`
//! WOULD PUBLISH IT.**
//!
//! Prints `{"shapes": [ShapeInfo, …]}` for every shape this daemon registers,
//! read through the one function `Hub::register` seeds a task's published info
//! from (`ShapeInfo::declared_by`) — so what this prints IS what a running
//! daemon of this commit serves on `shapes.list`, minus the runtime fields that
//! are at their fresh values here (`keys`, `subscribers`, `epoch`, counters).
//!
//! ## Why this exists
//!
//! `seam/tools/make-inventory.py` writes the seam kit's `inventory.json` — the
//! producer's surface as the producer states it, which `seamdiff --inventory`
//! routes every consumer read against. Its shape section used to come off a
//! RUNNING daemon, because `Shape::VERSION`/`SERVES` were trait defaults nobody
//! could scrape. That is still true of scraping, and no longer the only honest
//! read: the declaration is a set of consts, and this binary READS them rather
//! than guessing at them. A reviewer can regenerate the inventory with no daemon
//! in the room and see the diff, which is the property `make-inventory.py`'s own
//! header asks for.
//!
//! **Registration order is `ThreadManager::start_shapes`'s** — parents before
//! children, as `Hub::register` requires — and is asserted by
//! `tests/cell_manifest.rs::the_manifest_tool_lists_every_registered_shape`, so a
//! shape added to the daemon and not here is a red test rather than an inventory
//! with a hole in it.
//!
//! Read-only, no network, no store, no daemon: it constructs nothing but the
//! declarations.

use threads::shape::{Input, ShapeInfo};
use threads::shapes::{
    accounts::Accounts, boot::Boot, gauge_history::GaugeHistory, heartbeat::Heartbeat, log::Log, narration::Narration,
    nonidle::NonIdle, recent::Recent, recent_visits::RecentVisits, summary::Summary, threads::Threads, warnings::Warnings,
};

/// **EVERY SHAPE THIS PRODUCER REGISTERS, IN REGISTRATION ORDER.** The one list;
/// the test pins it against the daemon's own `start_shapes`.
pub fn declared() -> Vec<ShapeInfo> {
    let mut shapes = vec![
        ShapeInfo::declared_by::<Input, Accounts>(),
        ShapeInfo::declared_by::<Input, GaugeHistory>(),
        ShapeInfo::declared_by::<Input, Threads>(),
        ShapeInfo::declared_by::<Input, Summary>(),
        ShapeInfo::declared_by::<Input, Log>(),
        ShapeInfo::declared_by::<Input, Recent>(),
        ShapeInfo::declared_by::<Input, RecentVisits>(),
        ShapeInfo::declared_by::<Input, NonIdle>(),
        ShapeInfo::declared_by::<Input, Narration>(),
        ShapeInfo::declared_by::<Input, Heartbeat>(),
        ShapeInfo::declared_by::<Input, Warnings>(),
        ShapeInfo::declared_by::<Input, Boot>(),
    ];
    // `parent` is filled by `Hub::list` from the slot; filled here from the
    // same const so the offline form carries the edge too.
    for s in &mut shapes {
        s.parent = match s.name.as_str() {
            "threads/summary" | "threads/log" | "threads/recent-updates" | "threads/recent-visits" | "threads/non-idle" => {
                Some("threads".into())
            }
            "accounts/gauge-history" => Some("accounts".into()),
            _ => None,
        };
    }
    shapes
}

fn main() {
    let doc = serde_json::json!({
        "_": "GENERATED by `cargo run -q -p threads --bin shapes-manifest`: every shape this \
              producer registers, as `ShapeInfo::declared_by` reads it off the shape's consts. \
              Runtime fields are at their fresh values.",
        "_boot_id": serde_json::Value::Null,
        "shapes": declared(),
    });
    println!(
        "{}",
        serde_json::to_string_pretty(&doc).expect("a ShapeInfo serialises")
    );
}
