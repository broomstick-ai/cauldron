//! # The consumer seam — **A FACE HOLDS A MIRROR; IT DOES NOT ASK QUESTIONS.**
//!
//! **This directory is the REFERENCE.** It is authored once, here, in the
//! chassis repo; `scripts/vendor-chassis.sh` copies it into a consumer repo
//! beside the vendored crate; and each face's `src/seam/` is a COPY of it that
//! `tools/seamdiff` diffs byte-for-byte. `docs/consumer-seam.md` §7.1 is the
//! specification and §R3 is the reason it exists before the second copy: *"the
//! second copy's first commit is a diff of zero by construction."*
//!
//! The reference is DATA FOR A TEST, never a `use`. Nothing links it. It
//! compiles here — as its own crate, with its own conformance transcripts
//! replayed through [`Held::fold`] — so that "the reference is correct" is a
//! test result rather than a claim about a text file.
//!
//! ```text
//!   seam/mod.rs       this file — the handle, the lock, the divergence table
//!   seam/link.rs      ONE socket: connect / handshake / learn / subscribe /
//!                     deliver / reconnect / refuse / teardown
//!   seam/held.rs      Held { mirrors, book, promises } — pure, no tokio
//!   seam/view.rs      the read vocabulary over &Held — pure, and the ONLY
//!                     thing a face reads
//!   seam/commands.rs  the verbs, each answering a promise
//!   seam/ledger.rs    one thread's live log, read off the `threads/log` mirror
//!   seam/inventory.rs GENERATED — the producer's surface as a BUILD INPUT
//! ```
//!
//! ## The seventh file, and why the kit is where it lives
//!
//! [`inventory`] is generated by `tools/make-inventory.py` from
//! `seam/inventory.json`, in the same run, and it is the half that makes the
//! producer's surface a **build input of the consumer** rather than a fixture a
//! test tool reads when somebody runs it. One `shapewire::surface::Method` const
//! per method the producer dispatches, one `shapewire::surface::Carried` const
//! per cell it declares, and nothing else — so a method with no door and a cell
//! with no cargo have no name this seam can write, and the failure is rustc's
//! own, in the face's own build.
//!
//! It is in the **kit** and not per-consumer, on the operator's ruling, because
//! the kit is already the thing that carries *"the same"* by hash: §R3's *"a diff
//! of zero by construction"* now holds in the language the surface is compiled
//! in. Per-consumer generation would reintroduce exactly the drift the seam
//! exists to kill — two faces compiling against two surfaces at two commits.
//!
//! It is hand-edited by nobody. `tools/seamdiff --inventory` asserts it and
//! `inventory.json` are the same surface at the same `source_commit`, and
//! `vendor-chassis.sh` hashes it into `VENDORED` like every other file.
//!
//! ## The operator's ruling, and where it is enforced
//!
//! > *"We should not have new paths to request data. That's adding features to
//! > the producer that we didn't want to support. We should remove the ability
//! > to request data."*
//!
//! Structurally: no function in `view.rs` holds a [`link::Link`], so the render
//! path cannot issue a request even if somebody wanted it to; and
//! [`commands`]'s method table is the whole of what this seam can say, checked
//! against the producer's own inventory by `tools/seamdiff --inventory`.
//!
//! ## The divergence table — every line in the seam that may differ by face
//!
//! Each LIVE row is a `// SEAM-DIVERGE(D<n>)` … `// SEAM-END` fence in the
//! source. A difference outside a fence is a bug in the design, not a choice,
//! and `tools/seamdiff` is what says so.
//!
//! **Two fences, not eight.** `docs/consumer-seam.md` §5 enumerated eight
//! forced divergences under a sixty-line budget. Six of them turned out not to
//! be divergences in the seam at all, and the table records the disposition of
//! each rather than quietly dropping it — a dissolved divergence is a design
//! finding and `docs/consumer-seam.md` §5 carries the same table.
//!
//! | # | where | status | the AUI's | the terminal face's |
//! |---|---|---|---|---|
//! | D1 | `link.rs`, who may start the daemon | **DISSOLVED** → [`link::Supervisor`], a hook the face implements above the seam | `Some(hook)` | `None` |
//! | D2 | `link.rs`, the face's own two words | **FENCED** | `FACE = "aui"`, `ENV_PREFIX = "AUI_THREADS"` | `FACE = "tui"`, `ENV_PREFIX = "TUI_THREADS"` |
//! | D3 | `held.rs`, `Book::standing` | **FENCED** | no `narration/progress` — there is no spoken form for a progress line and the audio law forbids inventing one | all three narration channels |
//! | D4 | `commands.rs`, the verb set | **DISSOLVED** — a verb a face never calls is vocabulary, not policy. The reference carries every verb; which ones a face CALLS is above the seam. | calls `send create update seen event cancel` | calls `send create cancel` |
//! | D5 | how a face reaches the seam | **DISSOLVED** — [`Seam::start`] answers a `Seam`; where a face PUTS it (a `static OnceCell`, a field on `App`) is above the seam | a `static` | a field |
//! | D6 | the event adapter | **DISSOLVED** — [`link::SeamEvent`] rides a `broadcast` in both; a face that wants it on its own enum's channel spawns a four-line forwarder above the seam | `Event::Seam(e)` | `Ev::Seam(e)` |
//! | D7 | `ledger.rs`, the buffer policy | **DISSOLVED BY `threads/log`** — the window is the PRODUCER's (4,000 rows, published as `retained_items`), so there is no `OPEN_CAP` and no `TAIL_CAP` left to differ | — | — |
//! | D8 | project membership, pins, archived | **NEVER IN THE SEAM** — a consumer-side index, named in the design so nobody mistakes it for seam state | owns it | reads it |
//!
//! `view.rs` carries **zero** fenced lines, as the design predicted, and so now
//! do `commands.rs`, `ledger.rs` and this file.

use std::sync::Arc;

use std::sync::{Mutex, MutexGuard};

use tokio::sync::broadcast;

pub mod commands;
pub mod held;
/// **GENERATED. THE PRODUCER'S SURFACE.** See this module's own header; nothing
/// in this directory edits it and no face may.
pub mod inventory;
pub mod ledger;
pub mod link;
pub mod view;

#[allow(unused_imports)]
pub use held::{Fact, Held, Holding, LinkState, Settled};
pub use link::{SeamEvent, Supervision, Supervisor};

/// **WHAT A FACE CLAIMS IT WAS BUILT AGAINST**, on every subscribe, as
/// `consumer.shape_version`. Free text for a human — the ledger's own ruling is
/// that nothing compares it — and it is the vendor stamp rather than a date so
/// that `consumers` on `shapes/list` names a commit somebody can check out.
///
/// **Rewritten by `vendor-chassis.sh`** to the commit it vendored, and asserted
/// equal to `inventory.json`'s `source_commit` by `tools/seamdiff --inventory`.
/// A face does not edit it; the vendor bump does.
pub const SHAPE_VERSION: &str = "shapewire@3c6de48";

/// **THE INTEGER RULE 2.6 CHECKS — PER SHAPE, BECAUSE THE RULE IS PER SHAPE.**
///
/// Each entry is the contract version of that shape this seam was BUILT
/// against, sent as `version` on every subscribe of that shape; a producer that
/// does not serve it refuses with `version_refused`, which is the rule working
/// rather than a surprise at the operator's next keypress.
///
/// **It was one integer for every shape until R2.S8**, which was a latent lie:
/// a shape's version moves on its own, and one number for ten shapes can only
/// be right while all ten sit at the same version. `accounts` moving to 2 (its
/// `threads` cell is gone, and `view::running` reads `threads/non-idle`) is the
/// first time that mattered. Every shape the book can hold is listed, so the
/// table is a statement about each and not a default somebody forgot to
/// override; [`SHAPE_CONTRACT_DEFAULT`] covers only a shape added to the book
/// without a row here, and `seamdiff --inventory` checks every row against the
/// producer's `serves`.
///
/// **Not hand-moved to track the producer.** A version here changes when THIS
/// seam's reads change to what the new contract carries — never because the
/// inventory says a bigger number, which would make the handshake a tautology.
pub const SHAPE_CONTRACT_VERSIONS: &[(&str, u32)] = &[
    ("heartbeat", 1),
    ("threads/recent-updates", 1),
    ("threads/summary", 1),
    ("accounts", 2),
    ("threads/non-idle", 1),
    ("narration", 1),
    ("threads", 1),
    ("threads/log", 1),
    ("accounts/gauge-history", 1),
];

/// The version stated for a shape with no row in [`SHAPE_CONTRACT_VERSIONS`].
pub const SHAPE_CONTRACT_DEFAULT: u32 = 1;

/// The contract version this seam states for `shape` on its subscribe.
pub fn contract_version(shape: &str) -> u32 {
    SHAPE_CONTRACT_VERSIONS
        .iter()
        .find(|(s, _)| *s == shape)
        .map(|(_, v)| *v)
        .unwrap_or(SHAPE_CONTRACT_DEFAULT)
}

/// **HOW BIG THE EVENT BROADCAST IS, AND WHY THE NUMBER DOES NOT MATTER MUCH.**
///
/// Under the firehose this channel carried FACTS, so an overflow was a hole in
/// the truth and cost a `threads/status` resync plus a `threads/{id}/history`
/// page per affected thread. It now carries WAKE-UPS: the mirror applied the
/// frame before the wake-up was queued, so a dropped one costs nothing and the
/// next read sees the same state. 1,024 is generous for a channel whose loss is
/// free.
const EVENTS: usize = 1_024;

/// What a face holds. Cheap to clone.
pub struct Seam {
    pub held: Arc<Mutex<Held>>,
    pub link: link::Link,
    events: broadcast::Sender<SeamEvent>,
}

impl Seam {
    /// **START THE ONE SOCKET AND ANSWER THE HANDLE.**
    ///
    /// Where a face PUTS the handle is the face's business and was divergence
    /// D5 until this function existed: the AUI holds it in a `static OnceCell`
    /// because it has many tasks and no central owner; the terminal face holds
    /// it as a field on `App` because it has one loop that owns everything.
    /// Neither answer needs a line of the seam to change, so neither is a
    /// divergence any more.
    pub fn start(supervision: Supervision) -> Self {
        let held = Arc::new(Mutex::new(Held::new()));
        let (events, _) = broadcast::channel(EVENTS);
        let link = link::start(held.clone(), events.clone(), supervision);
        Seam {
            held,
            link,
            events,
        }
    }

    /// **THE ONE LOCK, AND IT IS A `std::sync::Mutex` ON PURPOSE.**
    ///
    /// Nothing awaits while holding it — the fold is one `Mirror::accept` plus
    /// two book writes, and a read is one projection — so an async mutex would
    /// buy nothing and cost the thing that matters: the AUI's row, tone and
    /// phone-projection paths are SYNC (`dispatch::thread_is_active` is called
    /// from a render walk) and an async lock would force a runtime into every
    /// one of them. `StatusTable` was behind exactly this kind of lock and every
    /// one of its readers stays a plain function call.
    ///
    /// Poison is recovered rather than propagated, which is this crate's
    /// existing idiom: a panic in one fold must not take the mirror away from
    /// the operator's interface for the rest of the process's life.
    pub fn lock(&self) -> MutexGuard<'_, Held> {
        self.held.lock().unwrap_or_else(|e| e.into_inner())
    }

    /// A wake-up stream. Every subscriber reads the mirror when it wakes; none
    /// of them reads state off the event, which is why a `Lagged` here needs no
    /// handler.
    ///
    /// A face whose loop has its own event enum spawns one forwarder over this
    /// — `while let Ok(e) = rx.recv().await { tx.send(Ev::Seam(e)) }` — above
    /// the seam. That forwarder was divergence D6; four lines in the face is
    /// cheaper than a fence in the seam.
    pub fn events(&self) -> broadcast::Receiver<SeamEvent> {
        self.events.subscribe()
    }

    /// Hold `(shape, key)`, subscribing if this is the first holder.
    pub async fn hold(&self, shape: &'static str, key: &str) {
        let fresh = self.lock().book.hold(shape, Some(key));
        if fresh {
            self.link.subscribe(shape, Some(key.to_string())).await;
        }
    }

    /// Let one hold go. The LAST holder letting go sends the keyed
    /// `unsubscribe`, which a long-lived face must actually do: `threads` and
    /// `threads/log` are on-demand, their roots grow for the life of a
    /// connection, and the AUI's connection lives for days.
    pub async fn release(&self, shape: &'static str, key: &str) {
        let last = self.lock().book.release(shape, Some(key));
        if last {
            self.link.unsubscribe(shape, Some(key.to_string())).await;
        }
    }

    /// Open a `threads/log` window on `thread`, closing the least recently
    /// opened one if the producer's `open_keys_per_conn` ceiling is already
    /// reached. The ceiling is read off `shapes/list`, never hardcoded, and
    /// asking for a ninth key is REFUSED rather than clamped — so this policy
    /// exists to stay inside a number the producer owns, not to guess it.
    pub async fn watch_log(&self, thread: &str) {
        let evict = {
            let g = self.lock();
            let open = g.book.keys_of(held::LOG);
            if open.iter().any(|k| k == thread) {
                None
            } else if open.len() >= ledger::capacity(&g) {
                open.first().cloned()
            } else {
                None
            }
        };
        if let Some(old) = evict {
            self.release(held::LOG, &old).await;
        }
        self.hold(held::LOG, thread).await;
    }

    pub async fn unwatch_log(&self, thread: &str) {
        self.release(held::LOG, thread).await;
    }

    /// Read something off the mirror under the one lock. Every face read goes
    /// through here, so "the render path holds the lock for exactly one
    /// projection" is visible at the call site.
    pub fn read<T>(&self, f: impl FnOnce(&Held) -> T) -> T {
        f(&self.lock())
    }

    /// The mutating twin, for [`ledger::claim`] — the only writer above the
    /// link, and the only thing it writes is this face's own output position.
    pub fn write<T>(&self, f: impl FnOnce(&mut Held) -> T) -> T {
        f(&mut self.lock())
    }
}
