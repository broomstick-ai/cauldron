#!/usr/bin/env python3
"""Record a conformance transcript from the LIVE producer.

`docs/consumer-seam.md` §7.3: the golden transcripts are *"scripted sessions
GENERATED BY THE PRODUCER"*. This is the generator. It connects to the chassis
door, learns, subscribes what it was told to subscribe, records every `shape`
frame verbatim in arrival order, and writes a `.jsonl` whose first line says
where the frames came from.

**READ-ONLY, AND STRUCTURALLY SO.** Three method names, the same three the live
probe sends and the same three the chassis answers out of itself:
`shapes/list`, `shapes/{shape}/subscribe`, `shapes/{shape}/unsubscribe`. No
command verb appears in this file.

    ./record-transcript.py <name> <shape>[:<key>] [<shape>[:<key>] …]
                           [--port 3653] [--seconds 6] [--out <dir>]

What it does NOT do is write the EXPECTATIONS. Those are computed once by
replaying the recorded frames through the reference's own `Held::fold`
(`cargo test --features bless` in `seam/`, which rewrites the `expect` lines)
and then committed. That split is deliberate: the frames are the producer's
and this script must not be able to invent one; the expectations are the
consumer's and must be produced by the code they lock.
"""

import json
import os
import sys
import time

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from importlib import import_module

_sl = import_module("shapes-list".replace("-", "_")) if False else None

# `shapes-list.py` is not an importable module name, so the three wire helpers
# are shared by exec-ing it rather than by duplicating them — one copy of the
# handshake, which is the point.
_ns: dict = {}
with open(os.path.join(os.path.dirname(os.path.abspath(__file__)), "shapes-list.py")) as fh:
    exec(compile(fh.read().replace('if __name__ == "__main__":\n    main()', ''),
                 "shapes-list.py", "exec"), _ns)
handshake, send_text, Frames = _ns["handshake"], _ns["send_text"], _ns["Frames"]

import re
import socket

#: The seam reference's own `mod.rs`, relative to this tool.
MOD_RS = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "mod.rs")


def contract_table(path=MOD_RS):
    """`SHAPE_CONTRACT_VERSIONS` and `SHAPE_CONTRACT_DEFAULT`, read out of `mod.rs`.

    **RULE 2.6 IS PER SHAPE**, so the version this recorder states on a
    subscribe is the one the seam reference states for THAT shape — `accounts`
    is 2 since R2.S8 and a recorder sending 1 is refused it. Read from the
    reference rather than restated here, so the two cannot drift.

    **RAISES rather than defaulting.** A recorder that silently stated 1 for a
    shape the reference states 2 for would record a refusal and call it a
    transcript; an unreadable table stops the run instead.
    """
    with open(path) as fh:
        text = fh.read()
    d = re.search(r"pub const SHAPE_CONTRACT_DEFAULT:\s*u32\s*=\s*(\d+)\s*;", text)
    t = re.search(r"pub const SHAPE_CONTRACT_VERSIONS:[^=]*=\s*&\[(.*?)\];", text, re.S)
    if not d or not t:
        raise ValueError(f"{path}: SHAPE_CONTRACT_VERSIONS / SHAPE_CONTRACT_DEFAULT not found")
    rows = {}
    for line in t.group(1).splitlines():
        line = line.strip()
        if not line or line.startswith("//"):
            continue
        m = re.fullmatch(r'\(\s*"([^"]+)"\s*,\s*(\d+)\s*\),?', line)
        if not m:
            raise ValueError(f"{path}: a SHAPE_CONTRACT_VERSIONS row does not parse: {line!r}")
        rows[m.group(1)] = int(m.group(2))
    if not rows:
        raise ValueError(f"{path}: SHAPE_CONTRACT_VERSIONS is empty")
    return rows, int(d.group(1))


def version_for(shape, table):
    rows, default = table
    return rows.get(shape, default)


def self_test(path=MOD_RS, lookup=version_for):
    """`./record-transcript.py --self-test` — the parser against the real table."""
    table = contract_table(path)
    assert table[0], "the table is empty"
    assert lookup("accounts", table) == 2, "accounts states 2 since R2.S8"
    assert lookup("heartbeat", table) == 1, "heartbeat states 1"
    assert lookup("no-such-shape", table) == table[1], "an unknown shape takes the default"
    print(f"self-test ok: {len(table[0])} rows, default {table[1]}")


def main():
    args = [a for a in sys.argv[1:]]
    port, seconds, out = 3653, 6.0, None
    rest = []
    i = 0
    while i < len(args):
        if args[i] == "--port":
            port = int(args[i + 1]); i += 2
        elif args[i] == "--seconds":
            seconds = float(args[i + 1]); i += 2
        elif args[i] == "--out":
            out = args[i + 1]; i += 2
        else:
            rest.append(args[i]); i += 1
    if rest == ["--self-test"]:
        self_test()
        return
    if len(rest) < 2:
        sys.exit(__doc__)
    try:
        table = contract_table()
    except (OSError, ValueError) as e:
        sys.exit(f"record-transcript.py: refusing to run — {e}")
    name, subs = rest[0], rest[1:]
    out = out or os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "conformance")
    os.makedirs(out, exist_ok=True)

    sock = socket.create_connection(("127.0.0.1", port), timeout=10)
    frames = Frames(sock, handshake(sock, "127.0.0.1", port))
    welcome = json.loads(frames.next_text())
    if welcome.get("type") != "welcome":
        sys.exit(f"first frame was not a welcome: {welcome}")
    if welcome.get("auth_required"):
        sys.exit("this daemon wants a secret; this script deliberately holds none")

    send_text(sock, json.dumps({"type": "request", "id": "L", "method": "shapes/list", "params": {}}))
    infos = None
    while infos is None:
        v = json.loads(frames.next_text())
        if v.get("type") == "response" and v.get("correlate") == "L":
            if v["outcome"].get("type") != "success":
                sys.exit(f"`shapes/list` refused: {v['outcome']}")
            infos = v["outcome"]["payload"]["shapes"]

    asked = []
    for n, spec in enumerate(subs):
        # `<shape>[:<key>][@<retain>]`. `@n` is rule 2.8's subscriber
        # parameter and it is here for one reason: `threads/log`'s window is
        # 4,000 rows, so an untrimmed recording is 1.7 MB of transcript for a
        # property that eight rows state just as well — AND the trimmed export
        # comes back `complete: false` with a `covers_since`, which is rule
        # 2.8's stated-truncation case the kit has to cover anyway.
        spec, _, retain = spec.partition("@")
        shape, _, key = spec.partition(":")
        params = {
            # Rule 2.1's identity. The RECORDER's own name, never a face's: a
            # transcript taken under `name: "aui"` would put a consumer in the
            # producer's ledger that is not running.
            "consumer": {
                "name": "transcript-recorder",
                "shape_version": "seam-reference",
                "pid": os.getpid(),
                "build": "record-transcript.py",
            },
            # Rule 2.6, PER SHAPE: the version the seam reference states for
            # this shape (`mod.rs`'s `SHAPE_CONTRACT_VERSIONS`).
            "version": version_for(shape, table),
        }
        if key:
            params["key"] = key
        if retain:
            params["retain"] = int(retain)
        asked.append({"shape": shape, "key": key or None, "params": params})
        send_text(sock, json.dumps({
            "type": "request", "id": f"S{n}",
            "method": f"shapes/{shape}/subscribe", "params": params,
        }))

    recorded, refusals = [], []
    sock.settimeout(1.0)
    deadline = time.time() + seconds
    while time.time() < deadline:
        try:
            v = json.loads(frames.next_text())
        except (TimeoutError, socket.timeout):
            continue
        except EOFError as e:
            sys.exit(f"the daemon closed the socket: {e}")
        if v.get("type") == "shape":
            recorded.append(v)
        elif v.get("type") == "response" and str(v.get("correlate", "")).startswith("S"):
            o = v.get("outcome", {})
            if o.get("type") != "success":
                refusals.append({"correlate": v["correlate"], "outcome": o})

    for n, a in enumerate(asked):
        p = {"key": a["key"]} if a["key"] else {}
        send_text(sock, json.dumps({
            "type": "request", "id": f"U{n}",
            "method": f"shapes/{a['shape']}/unsubscribe", "params": p,
        }))
    sock.close()

    path = os.path.join(out, f"{name}.jsonl")
    with open(path, "w") as fh:
        fh.write(json.dumps({"transcript": {
            "name": name,
            "source": "live producer",
            "recorded_at": time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime()),
            "daemon_boot_id": welcome.get("boot_id"),
            "subscribed": [{"shape": a["shape"], "key": a["key"]} for a in asked],
            "refusals": refusals,
            "shapes_served": sorted(s["name"] for s in infos),
            "note": "Frames recorded verbatim from the live daemon, in arrival "
                    "order. The `expect` lines are written by the reference's own "
                    "bless run and are the consumer half.",
        }}, sort_keys=True) + "\n")
        for f in recorded:
            fh.write(json.dumps({"frame": f}, sort_keys=True) + "\n")
    print(f"{path}: {len(recorded)} frame(s), {len(refusals)} refusal(s)")


if __name__ == "__main__":
    main()
